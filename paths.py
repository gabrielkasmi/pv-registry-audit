def resolve(path: Path) -> Path:
    """Return ``path``, raising a message that says what to do if it is missing."""
    if path.exists():
        return path
    where = "PV_AUDIT_DATA" if str(DATA) in str(path) else "the repository"
    raise FileNotFoundError(
        f"{path} not found.\n"
        f"The replication dataset is not part of this repository. Download it "
        f"from Zenodo (see README), then either unpack it at {REPO / 'data'} or "
        f"set {where} to its location."
    )


def describe() -> str:
    """One-line status of every declared path, for a quick sanity check."""
    import sys

    rows = []
    for name, value in sorted(globals().items()):
        if name.isupper() and isinstance(value, Path) and name not in {"REPO", "DATA"}:
            mark = "ok " if value.exists() else "MISSING"
            rows.append(f"  {mark}  {name:28} {value}")
    header = f"repository : {REPO}\ndata       : {DATA}\nfigures    : {FIGURES}\n"
    text = header + "\n".join(rows)
    print(text, file=sys.stdout)
    return text


if __name__ == "__main__":
    describe()
