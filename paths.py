"""Single source of truth for where the data lives.

Every notebook and script in this repository reads its inputs through this
module. Nothing hard-codes a relative path, so moving the data does not mean
editing thirty files: it means setting one environment variable.

The code ships with the repository, the data does not. Download the replication
dataset from Zenodo (see README), unpack it, and either place it at
``<repo>/data`` or point ``PV_AUDIT_DATA`` at wherever you put it::

    export PV_AUDIT_DATA=/scratch/pv-audit-data

Two directories, and the distinction matters when reproducing.

``data/source`` holds inputs that this repository does not produce: the
detection product, the registries, administrative boundaries, and the manual
annotations. Nothing here is regenerated by any script; it is the starting
point. The annotations sit here rather than under ``intermediate`` on purpose.
They are 31,853 human judgements, not a derived quantity, and no amount of
recomputation would recreate them.

``data/intermediate`` holds what the pipeline computes on the way to the paper's
numbers. It ships so that any single step can be re-run without replaying the
whole chain, and so that a reader can check one figure without downloading five
gigabytes of third-party dumps.

Most intermediate files are reproducible from ``data/source`` by the scripts in
``code/``, in the order given by REPRODUCE.md. Two are not, because their inputs
are bulk third-party downloads that this repository does not redistribute: the
OpenStreetMap PV extract needs the France ``.pbf``, and the imagery dates need
the IGN mosaicking graphs. ``data/MANIFEST.csv`` states, file by file, which is
which and what produces it. When in doubt, read the manifest rather than
guessing from the folder name.
"""

