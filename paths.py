def _find_repo(start: Path | None = None) -> Path:
    """Walk up until the marker file that sits at the repository root."""
    start = (start or Path.cwd()).resolve()
    for parent in [start, *start.parents]:
        if (parent / "paths.py").exists() and (parent / "code").is_dir():
            return parent
    # Fall back to this file's own location, which is correct whenever the
    # module was imported rather than copied.
    return Path(__file__).resolve().parent


